#!/usr/bin/env node
/**
 * Emit lib/networks/creditPartnershipModel.ts and
 * lib/networks/creditPartnershipCoverage.ts from the M9 sidecar
 * (scripts/data/credit-m9-partnership-sidecar.json, written by
 * parse-credit-m9-partnerships.mjs).
 *
 * The coverage file is deliberately tiny and separate: lib/networks/tabs.ts
 * gates the Partnerships tab on it, and the gate must never drag the full
 * 600-edge model into a chunk that only needs the slug list.
 *
 *   node scripts/generate-credit-partnership-model.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const sidecar = JSON.parse(
  readFileSync(path.join(here, "data", "credit-m9-partnership-sidecar.json"), "utf-8"),
);

const { meta, taxonomy, nodes, edges, chainStrips, selfRows } = sidecar;
if (!meta || !taxonomy || !nodes || !edges || !chainStrips || !selfRows) {
  console.error("Sidecar incomplete — re-run parse-credit-m9-partnerships.mjs.");
  process.exit(1);
}
if (meta.rowTotal !== 687) {
  console.error(`Sidecar rowTotal ${meta.rowTotal} !== 687.`);
  process.exit(1);
}
if (meta.subjects.length !== 14) {
  console.error(`Expected 14 subjects, found ${meta.subjects.length}.`);
  process.exit(1);
}
if (taxonomy.length !== 10) {
  console.error(`Expected 10 taxonomy categories, found ${taxonomy.length}.`);
  process.exit(1);
}
for (const e of edges) {
  if (e.a >= e.b) {
    console.error(`Edge pair not sorted: ${e.a}|${e.b}`);
    process.exit(1);
  }
  if (!nodes[e.a] || !nodes[e.b]) {
    console.error(`Edge references missing node: ${e.a}|${e.b}`);
    process.exit(1);
  }
}

const nodeEntries = Object.keys(nodes)
  .sort()
  .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(nodes[id])},`)
  .join("\n");
const edgeEntries = edges.map((e) => `  ${JSON.stringify(e)},`).join("\n");
const stripEntries = Object.keys(chainStrips)
  .sort()
  .map((slug) => `  ${JSON.stringify(slug)}: ${JSON.stringify(chainStrips[slug])},`)
  .join("\n");
const selfRowEntries = selfRows.map((r) => `  ${JSON.stringify(r)},`).join("\n");

const model = `// GENERATED by scripts/generate-credit-partnership-model.mjs — do not hand-edit.
// Source: scripts/data/credit-m9-partnership-sidecar.json (parsed from the
// CAN-81 partnership dataset, ${meta.rowTotal} sourced rows across the 14 covered
// entities). Normalisation model: docs/credit/partnership-model.md.
// First consumer: the Partnerships tab RelationshipExplorer (CAN-83/86).

export type PartnershipCategory =
  | "integration_technical"
  | "liquidity_provider"
  | "oracle"
  | "custody"
  | "chain_deployment"
  | "institutional_tradfi"
  | "security_audit"
  | "governance_dao"
  | "grant_investment"
  | "distribution_frontend";

export type PartnershipStatus = "active" | "deprecated" | "announced";
export type PartnershipDirection = "inbound" | "outbound" | "mutual";
export type PartnerKind = "protocol" | "service" | "institution" | "dao";

export interface PartnerNode {
  /** Canonical id: store slug for on-platform partners, kebab name otherwise. */
  id: string;
  name: string;
  /** Present only when the partner is an on-platform entity (/networks/[slug]). */
  slug?: string;
  /** The 14 dataset subjects carry subject: true plus their Credit tag. */
  subject?: boolean;
  tag?: string;
  degree: number;
  /** 0..1 — 0.6 x max incident edge weight + 0.4 x normalised log degree. */
  weight: number;
  kind: PartnerKind;
  /** CAN-88 comment: curator role flag, NOT an 11th category. */
  role?: "risk_curator";
}

export interface PartnershipEdgeRow {
  /** Which of the 14 subjects contributed this dataset row. */
  subject: string;
  /** Product/scope qualifier collapsed off the partner name ("CCIP", "PSM"). */
  qualifier?: string;
  direction: PartnershipDirection;
  status: PartnershipStatus;
  startDate: string | null;
  description: string;
  sourceLabel: string;
  sourceUrl: string;
  usdFigure?: number;
}

export interface PartnershipEdge {
  /** Sorted pair of node ids (a < b). */
  a: string;
  b: string;
  category: PartnershipCategory;
  /** Relative to \`a\`; "mutual" when either side says so or both sides listed it. */
  direction: PartnershipDirection;
  /** active > announced > deprecated across the merged rows. */
  status: PartnershipStatus;
  /** 0..1 — log10(usd)/10 clamped [0.3, 1] when a source states a figure, else the categorical default. */
  weight: number;
  usdFigure?: number;
  /** Both subjects listed the relationship; deduped to this one edge. */
  mergedFromBoth?: boolean;
  rows: PartnershipEdgeRow[];
}

export interface ChainDeploymentEntry {
  chain: string;
  status: PartnershipStatus;
  sourceUrl: string;
  sourceLabel: string;
}

export interface PartnershipSelfRow {
  subject: string;
  category: PartnershipCategory;
  partnerName: string;
  description: string;
  sourceUrl: string;
  /** "self" = the subject's own org/DAO row; "infrastructure" = own tooling. */
  kind: "self" | "infrastructure";
}

export const PARTNERSHIP_TAXONOMY: { id: PartnershipCategory; label: string }[] = ${JSON.stringify(taxonomy, null, 2)};

export const PARTNER_NODES: Record<string, PartnerNode> = {
${nodeEntries}
};

export const PARTNERSHIP_EDGES: PartnershipEdge[] = [
${edgeEntries}
];

/** chain_deployment rows render as badge strips, never as graph nodes (CAN-88). */
export const CHAIN_DEPLOYMENTS: Record<string, ChainDeploymentEntry[]> = {
${stripEntries}
};

/** Evidenced rows about the subject itself (own DAO, own oracles, multisigs). */
export const PARTNERSHIP_SELF_ROWS: PartnershipSelfRow[] = [
${selfRowEntries}
];

export const PARTNERSHIP_ROW_TOTAL = ${meta.rowTotal};
`;

const coverage = `// GENERATED by scripts/generate-credit-partnership-model.mjs — do not hand-edit.
// Tiny on purpose: lib/networks/tabs.ts gates the Partnerships tab on this
// list without pulling the full partnership model into its chunk.

/** The 14 Credit entities covered by the M9 partnership dataset (CAN-81).
 * The 8 outstanding Credit entities are parked to M11 pending CAN-48 tags. */
export const PARTNERSHIP_COVERED_SLUGS: readonly string[] = ${JSON.stringify(meta.subjects, null, 2)};
`;

const modelTarget = path.resolve(here, "..", "lib", "networks", "creditPartnershipModel.ts");
const coverageTarget = path.resolve(here, "..", "lib", "networks", "creditPartnershipCoverage.ts");
writeFileSync(modelTarget, model);
writeFileSync(coverageTarget, coverage);
console.log(
  `Wrote ${Object.keys(nodes).length} nodes, ${edges.length} edges, ${Object.keys(chainStrips).length} chain strips, ${selfRows.length} self rows -> ${path.relative(process.cwd(), modelTarget)}`,
);
console.log(`Wrote ${meta.subjects.length} covered slugs -> ${path.relative(process.cwd(), coverageTarget)}`);
