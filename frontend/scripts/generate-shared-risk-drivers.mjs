#!/usr/bin/env node
/**
 * Emit lib/networks/sharedRiskDrivers.ts from the authoritative M6/M7 dataset
 * (scripts/data/credit-assets-risks.json, top-level `shared_risk_drivers`).
 *
 * The drivers live only in the committed dataset JSON, not in KV; generating a
 * small typed module keeps the multi-thousand-line JSON out of the server
 * bundle and gives M8 (competitor join) and M9 (RelationshipExplorer) a ready
 * import. Re-run whenever the dataset JSON changes.
 *
 *   node scripts/generate-shared-risk-drivers.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dataset = JSON.parse(
  readFileSync(path.join(here, "data", "credit-assets-risks.json"), "utf-8"),
);

const drivers = dataset.shared_risk_drivers;
if (!Array.isArray(drivers) || drivers.length === 0) {
  console.error("No shared_risk_drivers in credit-assets-risks.json.");
  process.exit(1);
}

/**
 * Audit / bug-bounty firms among the counterparty drivers. The dataset prose:
 * "Shared auditors are a weaker signal than shared oracles, so render them in
 * a secondary group rather than alongside real dependencies."
 */
const AUDIT_FIRMS = new Set([
  "Immunefi",
  "PeckShield",
  "Sherlock",
  "ChainSecurity",
  "OpenZeppelin",
]);

const entityCount = dataset.entities.length;
const rows = drivers.map((d) => ({
  kind: d.kind,
  label: d.label,
  entityCount: d.entity_count,
  entities: d.entities,
  audit: AUDIT_FIRMS.has(d.label),
}));

for (const r of rows) {
  if (r.kind !== "asset" && r.kind !== "counterparty") {
    console.error(`Unexpected driver kind "${r.kind}" for ${r.label}.`);
    process.exit(1);
  }
  if (!Array.isArray(r.entities) || r.entities.length !== r.entityCount) {
    console.error(`entity_count mismatch for ${r.label}.`);
    process.exit(1);
  }
}

const entries = rows
  .map(
    (r) =>
      `  ${JSON.stringify(r.label.toUpperCase())}: { kind: ${JSON.stringify(r.kind)}, label: ${JSON.stringify(r.label)}, entityCount: ${r.entityCount}, entities: ${JSON.stringify(r.entities)}, audit: ${r.audit} },`,
  )
  .join("\n");

const out = `// GENERATED by scripts/generate-shared-risk-drivers.mjs — do not hand-edit.
// Source: scripts/data/credit-assets-risks.json (shared_risk_drivers,
// compiled ${dataset.generated}). Risk drivers appearing in 3+ of the
// ${entityCount} in-scope Credit entities' risk tables; \`audit\` marks
// audit/bounty firms (dataset: weaker signal, render as a secondary group).

export interface SharedRiskDriver {
  kind: "asset" | "counterparty";
  label: string;
  /** How many of the ${entityCount} in-scope Credit entities carry this driver. */
  entityCount: number;
  entities: string[];
  /** Audit/bounty firm — weaker signal than a shared oracle or issuer. */
  audit: boolean;
}

/** Keyed by UPPERCASE driver label (join key for linkedAssets/linkedPartners). */
export const SHARED_RISK_DRIVERS: Record<string, SharedRiskDriver> = {
${entries}
};

/** Total in-scope Credit entities the counts are out of. */
export const SHARED_DRIVER_ENTITY_TOTAL = ${entityCount};
`;

const target = path.resolve(here, "..", "lib", "networks", "sharedRiskDrivers.ts");
writeFileSync(target, out);
console.log(`Wrote ${rows.length} drivers -> ${path.relative(process.cwd(), target)}`);
