#!/usr/bin/env node
/**
 * Emit lib/networks/creditCompetitorModel.ts from the M8 sidecar
 * (scripts/data/credit-m8-store-patch.json, written by
 * parse-credit-m8-competitors.mjs).
 *
 * Node/edge shaped ON PURPOSE: M9's RelationshipExplorer consumes nodes +
 * edges + a category taxonomy, so the competitor graph ships ready for it
 * with no rewrite (the recorded M6/M7 sequencing compromise). Cohorts are
 * COMMITTED here rather than derived from profile.tags at runtime, which
 * keeps dev and prod cohorts identical (maple's bootstrap/KV tag divergence)
 * and keeps percentile denominators deterministic.
 *
 *   node scripts/generate-credit-competitor-model.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const sidecar = JSON.parse(
  readFileSync(path.join(here, "data", "credit-m8-store-patch.json"), "utf-8"),
);

const { nodes, edges, tagCohorts, riskCohorts, tierB } = sidecar;
if (!nodes || !edges || !tagCohorts || !riskCohorts || !tierB) {
  console.error("Sidecar missing nodes/edges/cohorts/tierB — re-run parse-credit-m8-competitors.mjs.");
  process.exit(1);
}

const tagged = Object.values(tagCohorts).flat();
if (tagged.length !== 32 || new Set(tagged).size !== 32) {
  console.error(`Expected 32 unique tagged slugs, found ${tagged.length}.`);
  process.exit(1);
}
for (const e of edges) {
  if (e.a >= e.b) {
    console.error(`Edge pair not sorted: ${e.a}|${e.b}`);
    process.exit(1);
  }
}

const fmt = (v) => JSON.stringify(v);

const nodeEntries = Object.keys(nodes)
  .sort()
  .map((slug) => `  ${fmt(slug)}: ${JSON.stringify(nodes[slug])},`)
  .join("\n");

const edgeEntries = edges.map((e) => `  ${JSON.stringify(e)},`).join("\n");
const tierBEntries = tierB.map((r) => `  ${JSON.stringify(r)},`).join("\n");

const out = `// GENERATED by scripts/generate-credit-competitor-model.mjs — do not hand-edit.
// Source: scripts/data/credit-m8-store-patch.json (parsed from the M8
// competitor dataset compiled ${sidecar.compiledAt}). Reciprocity is closed at
// parse time and asserted at store level by scripts/verify-m8-reciprocity.mjs.
// Nodes + edges are shaped for M9's RelationshipExplorer (later consumer).

export type CreditCompetitorTag = "Lending" | "Leveraged Yield" | "Fixed Income";

export interface CompetitorNode {
  slug: string;
  name: string;
  tag: CreditCompetitorTag;
  entityType: "protocol" | "risk-curator";
  /** t3tris-finance: provisional Leveraged Yield fit (dataset flag). */
  tagFit?: "partial";
  /** boros -> "pendle": shared parent; never render the pair as plain rivals. */
  parentSlug?: string;
  /** Winding down / sunset / dormant (entityStatus overrides carry the label). */
  nonSteadyState?: boolean;
  /** "not-applicable" = curator with no contracts (Steakhouse); "unverified" =
   * zero audits in DefiLlama's record, an open verification item NOT a finding. */
  auditStatus: "audited" | "unverified" | "not-applicable";
  dataQualityFlags?: string[];
}

export interface CompetitorEdge {
  /** Sorted pair (a < b); reciprocity is closed by construction. */
  a: string;
  b: string;
  sharedTag: boolean;
  /** boros|pendle only: same team and brand. */
  sharedParent?: boolean;
  /** Pair is simultaneously partner and competitor (CAN-84 comment). */
  alsoPartner?: boolean;
}

export interface TierBRow {
  name: string;
  type: string;
  competesWithTags: CreditCompetitorTag[];
  /** Off-platform: never clickable. */
  note: string;
}

/** Committed per-tag cohorts (percentile denominators). NOT profile.tags. */
export const TAG_COHORTS: Record<CreditCompetitorTag, string[]> = ${JSON.stringify(tagCohorts, null, 2)};

/** CAN-73 risk-comparison cohorts: only the 14 entities with TypedRisks.
 * Composites are never compared across tags (docs/credit/risk-taxonomy.md). */
export const RISK_COHORTS: Record<CreditCompetitorTag, string[]> = ${JSON.stringify(riskCohorts, null, 2)};

export const COMPETITOR_NODES: Record<string, CompetitorNode> = {
${nodeEntries}
};

export const COMPETITOR_EDGES: CompetitorEdge[] = [
${edgeEntries}
];

/** Off-platform competitors (CeFi, tokenised treasuries, benchmarks, non-EVM). */
export const TIER_B_ROWS: TierBRow[] = [
${tierBEntries}
];

/** Total tagged Credit entities across the three cohorts. */
export const CREDIT_TAGGED_TOTAL = ${tagged.length};
`;

const target = path.resolve(here, "..", "lib", "networks", "creditCompetitorModel.ts");
writeFileSync(target, out);
console.log(
  `Wrote ${Object.keys(nodes).length} nodes, ${edges.length} edges, ${tierB.length} tier-B rows -> ${path.relative(process.cwd(), target)}`,
);
